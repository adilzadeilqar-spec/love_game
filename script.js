/*
    ============================================================
    ИГРА «КТО КОГО БОЛЬШЕ ЛЮБИТ?»
    ============================================================

    Назначение:
    - Кнопка «Аксана → Илгар» является неправильным ответом.
    - На компьютере она убегает от курсора.
    - На телефоне она убегает от пальца.
    - Нажать неправильную кнопку невозможно.
    - Кнопка «Илгар → Аксана» показывает победное сообщение.

    Технологии:
    - Vanilla JavaScript.
    - Без сторонних библиотек.
    - Поддержка desktop и mobile.

    ============================================================
*/

// Получаем правильную кнопку.
const correctButton = document.getElementById("correctButton");

// Получаем убегающую кнопку.
const runawayButton = document.getElementById("runawayButton");

// Получаем контейнер для результата.
const result = document.getElementById("result");

// ------------------------------------------------------------
// Функция перемещения неправильной кнопки.
// ------------------------------------------------------------

function moveButton() {

    // Получаем ширину окна браузера.
    const screenWidth = window.innerWidth;

    // Получаем высоту окна браузера.
    const screenHeight = window.innerHeight;

    // Получаем текущую ширину кнопки.
    const buttonWidth = runawayButton.offsetWidth;

    // Получаем текущую высоту кнопки.
    const buttonHeight = runawayButton.offsetHeight;

    // Оставляем небольшой отступ от краёв экрана.
    const margin = 20;

    // Рассчитываем максимально допустимую координату X.
    const maxX = screenWidth - buttonWidth - margin;

    // Рассчитываем максимально допустимую координату Y.
    const maxY = screenHeight - buttonHeight - margin;

    // Генерируем случайную координату X.
    const randomX = margin + Math.random() * maxX;

    // Генерируем случайную координату Y.
    const randomY = margin + Math.random() * maxY;

    // Переводим кнопку в фиксированное положение относительно экрана.
    runawayButton.style.position = "fixed";

    // Устанавливаем новое положение по горизонтали.
    runawayButton.style.left = `${randomX}px`;

    // Устанавливаем новое положение по вертикали.
    runawayButton.style.top = `${randomY}px`;
}

// ------------------------------------------------------------
// Компьютер: кнопка убегает при наведении мыши.
// ------------------------------------------------------------

runawayButton.addEventListener("mouseenter", () => {

    // Перемещаем кнопку.
    moveButton();
});

// ------------------------------------------------------------
// Телефон: кнопка убегает при попытке прикосновения.
// ------------------------------------------------------------

runawayButton.addEventListener("touchstart", (event) => {

    // Отменяем стандартное действие браузера.
    event.preventDefault();

    // Перемещаем кнопку.
    moveButton();
});

// ------------------------------------------------------------
// Дополнительная защита от обычного клика.
// ------------------------------------------------------------

runawayButton.addEventListener("click", (event) => {

    // Отменяем действие клика.
    event.preventDefault();

    // Ещё раз перемещаем кнопку.
    moveButton();
});

// ------------------------------------------------------------
// Правильный ответ.
// ------------------------------------------------------------

correctButton.addEventListener("click", () => {

    // Показываем поздравление.
    result.textContent = "❤️ Конечно, Илгар! (01:05 - пишу прогу) ❤️";

    // Увеличиваем кнопку.
    correctButton.style.transform = "scale(1.15)";
});
